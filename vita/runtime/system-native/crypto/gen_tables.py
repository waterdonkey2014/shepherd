#!/usr/bin/env python3
"""SHEPHERD-VITA: derives every constant table of vita_crypto.c from its mathematical definition (nothing is copied or
downloaded) and writes vita_crypto_tables.h. Run: python3 gen_tables.py > vita_crypto_tables.h
  AES (FIPS 197 5.1.1): S-box = affine transform of the multiplicative inverse in GF(2^8) mod x^8+x^4+x^3+x+1; inverse S-box.
  SHA-1 (FIPS 180-4 4.2.1): K = floor(2^30 * sqrt(2, 3, 5, 10)); its H0 (5.3.1) is a fixed byte pattern, written in the C code.
  SHA-256 (FIPS 180-4 4.2.2/5.3.3): K = first 32 bits of the fractional parts of the cube roots of the first 64 primes;
          H0 = same of the square roots of the first 8 primes.
  SHA-512 (4.2.3/5.3.5): 64-bit versions over the first 80 primes; SHA-384 (5.3.4) H0 = square roots of the 9th..16th primes.
  MD5 (RFC 1321 3.4): T[i] = floor(2^32 * |sin(i)|), i = 1..64 (exact rational bound check below).
Integer roots are exact (isqrt on scaled integers), so the tables do not depend on floating point except MD5's sin, which is
checked against a 120-bit Taylor evaluation."""
from math import isqrt
from fractions import Fraction

def primes(n):
    out, k = [], 2
    while len(out) < n:
        if all(k % p for p in out if p * p <= k): out.append(k)
        k += 1
    return out

def icbrt(n):
    x = 1 << ((n.bit_length() + 2) // 3 + 1)
    while True:
        y = (2 * x + n // (x * x)) // 3
        if y >= x: break
        x = y
    while x * x * x > n: x -= 1
    while (x + 1) ** 3 <= n: x += 1
    return x

def frac_root(p, root, bits):
    # floor(frac(p^(1/root)) * 2^bits), exact
    if root == 2: v = isqrt(p << (2 * bits))
    else: v = icbrt(p << (3 * bits))
    return v & ((1 << bits) - 1)

def gf_mul(a, b):
    r = 0
    while b:
        if b & 1: r ^= a
        a <<= 1
        if a & 0x100: a ^= 0x11B
        b >>= 1
    return r

def aes_sbox():
    inv = [0] * 256
    for a in range(1, 256):
        for b in range(1, 256):
            if gf_mul(a, b) == 1: inv[a] = b; break
    s = []
    for a in range(256):
        b = inv[a]; c = 0x63
        r = b
        for sh in (1, 2, 3, 4): r ^= ((b << sh) | (b >> (8 - sh))) & 0xFF
        s.append(r ^ c)
    si = [0] * 256
    for i, v in enumerate(s): si[v] = i
    return s, si

def sin_frac(i):
    # |sin(i)| with ~120 bits via Taylor series on a rational argument reduced by multiples of pi (pi from Machin's formula)
    prec = 1 << 160
    def arctan_inv(x):
        s, t, n, sign = 0, prec // x, 1, 1
        while t:
            s += sign * t // n
            t //= x * x; n += 2; sign = -sign
        return s
    pi = 4 * (4 * arctan_inv(5) - arctan_inv(239))
    x = i * prec
    k = x // pi; x -= k * pi                       # x in [0, pi): sin has the sign of (-1)^k, |sin| is what MD5 uses
    s, t, n = 0, x, 1
    while t:
        s += t
        t = -t * x * x // ((n + 1) * (n + 2) * prec * prec); n += 2
    return abs(s)  # scaled by prec

def emit(name, ctype, vals, per, fmt):
    print(f"static const {ctype} {name} [{len(vals)}] = {{")
    for i in range(0, len(vals), per):
        print("\t" + ", ".join(fmt.format(v) for v in vals[i:i + per]) + ",")
    print("};")

pr = primes(80)
print("/* GENERATED by gen_tables.py (see its header for the derivations). Do not edit. */")
print("#pragma once")
print("#include <stdint.h>")
s, si = aes_sbox()
emit("aes_sbox", "uint8_t", s, 16, "0x{:02x}")
emit("aes_inv_sbox", "uint8_t", si, 16, "0x{:02x}")
emit("sha1_k", "uint32_t", [isqrt(n << 60) for n in (2, 3, 5, 10)], 4, "0x{:08x}u")
emit("sha256_k", "uint32_t", [frac_root(p, 3, 32) for p in pr[:64]], 8, "0x{:08x}u")
emit("sha256_h0", "uint32_t", [frac_root(p, 2, 32) for p in pr[:8]], 8, "0x{:08x}u")
emit("sha512_k", "uint64_t", [frac_root(p, 3, 64) for p in pr[:80]], 4, "0x{:016x}ull")
emit("sha512_h0", "uint64_t", [frac_root(p, 2, 64) for p in pr[:8]], 4, "0x{:016x}ull")
emit("sha384_h0", "uint64_t", [frac_root(p, 2, 64) for p in pr[8:16]], 4, "0x{:016x}ull")
prec = 1 << 160
md5 = []
for i in range(1, 65):
    v = sin_frac(i)
    t = (v << 32) // prec
    md5.append(t)
emit("md5_t", "uint32_t", md5, 8, "0x{:08x}u")
