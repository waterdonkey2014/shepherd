#!/usr/bin/env python3
"""SHEPHERD-VITA: generates pal_vita_stubs.c -- one loud, failing stub for every native entry point that the packaged
linux-arm BCL DECLARES (AsmSize pinvokes census) and that no hand-written shim file implements.

  gen_stubs.py <pinvokes.tsv> <runtime checkout> <out.c> <defined-symbols.txt>
  (defined-symbols.txt: one symbol per line, the `nm --defined-only` of the compiled hand-written shim objects)

Why: with direct-pinvoke AOT every P/Invoke of an AOT'd assembly is a link-time symbol, and interpreted assemblies resolve
through the static P/Invoke table; a stub turns "undefined symbol" / EntryPointNotFoundException into the API's documented
failure, logged once ("N> STUB lib!entry ..." in the host log). Return values follow each library's failure convention:
  libSystem.Native       Interop.Error returns -> Error_ENOTSUP; pointers -> NULL; MMap -> MAP_FAILED; other ints -> -1
                         (errno = ENOTSUP); void -> nothing
  ...Cryptography...     pointers -> NULL, ints -> 0 (OpenSSL failure); the crypto error slot is set (managed code throws
                         CryptographicException "not supported by the PS Vita crypto shim")
  ...Compression (Brotli) / Globalization / Net.Security  -> 0 / NULL (failure / "unavailable")
The C return type comes from the upstream PALEXPORT prototype (pointer vs integer vs 64-bit), the "is a PAL Error"
decision from the managed signature. Parameters are not declared (the callee never reads them; ARM EABI lets the caller
pass any arguments to a function that ignores them)."""
import re, sys, os, glob

tsv, runtime, out, defined_list = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4]

LIBS = {
    "libSystem.Native": "native",
    "libSystem.Security.Cryptography.Native.OpenSsl": "crypto",
    "libSystem.IO.Compression.Native": "zero",
    "libSystem.Globalization.Native": "zero",
    "libSystem.Net.Security.Native": "zero",
    "libhostpolicy": "zero",
}
HDR_DIRS = ["src/native/libs/System.Native", "src/native/libs/System.Security.Cryptography.Native",
            "src/native/libs/System.IO.Compression.Native", "src/native/libs/System.Globalization.Native",
            "src/native/libs/System.Net.Security.Native", "src/native/external/brotli/include/brotli"]

decl = {}   # (lib, entry) -> managed return type
for line in open(tsv):
    f = line.rstrip("\n").split("\t")
    if len(f) < 4 or f[0] == "assembly" or f[1] not in LIBS: continue
    decl.setdefault((f[1], f[2]), f[3].split(" ")[0])

defined = set(l.strip() for l in open(defined_list) if l.strip())

protos = {}
for d in HDR_DIRS:
    for h in glob.glob(os.path.join(runtime, d, "*.h")):
        txt = open(h, errors="replace").read()
        for m in re.finditer(r"(?:PALEXPORT|FUNCTIONEXPORT|BROTLI_DEC_API|BROTLI_ENC_API)\s+([^;{()]*?)\s*(?:FUNCTIONCALLINGCONVENCTION\s+)?\b([A-Za-z_]\w*)\s*\(", txt):
            protos.setdefault(m.group(2), (" ".join(m.group(1).split()), os.path.relpath(h, runtime)))

def ctype(entry, managed):
    rt = protos.get(entry, (None, None))[0]
    if rt is None:
        rt = {"Void": "void", "Int64": "int64_t", "UInt64": "uint64_t", "Double": "double", "Byte*": "void *", "Void*": "void *"}.get(managed, "int32_t")
    rt = rt.replace("const ", "").strip()
    if "*" in rt or "STACK_OF" in rt: return "void *"
    if rt == "void": return "void"
    if rt in ("int64_t", "uint64_t", "long long", "unsigned long long"): return rt
    if rt in ("double", "float"): return rt
    return "intptr_t" if rt in ("intptr_t", "uintptr_t", "size_t", "ssize_t") else "int32_t"

missing, noproto = [], []
for (lib, entry), managed in sorted(decl.items()):
    if entry in defined: continue
    missing.append((lib, entry, managed))
    if entry not in protos: noproto.append(entry)

o = []
o.append("/* GENERATED by vita/runtime/system-native/gen_stubs.py -- do not edit. One failing, logged-once stub per entry point")
o.append(" * the packaged BCL declares and no shim file implements (see the generator's docstring for the return conventions). */")
o.append("#include <errno.h>\n#include <stddef.h>\n#include <stdint.h>\n")
o.append("void shepherd_vita_native_log (const char *msg);")
o.append("void shepherd_vita_crypto_unsupported (void);   /* pal_vita_crypto.c: sets the error the managed side reads */")
o.append("static void stub_note (volatile int *done, const char *what)\n{\n\tif (!*done) {\n\t\t*done = 1;\n\t\tshepherd_vita_native_log (what);\n\t}\n}\n")
o.append("#define ERROR_ENOTSUP 0x1003D   /* pal_error_common.h Error_ENOTSUP */\n")
counts = {}
for lib, entry, managed in missing:
    kind = LIBS[lib]; ct = ctype(entry, managed)
    if ct == "void": ret, how = "", "nothing"
    elif kind == "native":
        if managed == "Interop/Error": ret, how = "return ERROR_ENOTSUP;", "Error_ENOTSUP"
        elif entry == "SystemNative_MMap": ret, how = "errno = ENOTSUP; return (void *) -1;", "MAP_FAILED, errno ENOTSUP"
        elif ct == "void *": ret, how = "errno = ENOTSUP; return NULL;", "NULL, errno ENOTSUP"
        else: ret, how = "errno = ENOTSUP; return -1;", "-1, errno ENOTSUP"
    elif kind == "crypto":
        ret = "shepherd_vita_crypto_unsupported (); return " + ("NULL;" if ct == "void *" else "0;")
        how = "NULL" if ct == "void *" else "0 (failure)"
    else:
        ret, how = ("return NULL;" if ct == "void *" else "return 0;"), ("NULL" if ct == "void *" else "0")
    msg = f"STUB {lib}!{entry} called: not supported on the PS Vita (returns {how})"
    src = protos.get(entry, (None, "no upstream prototype: type from the managed signature"))[1]
    o.append(f"/* {src} */")
    o.append(f"{ct} {entry} (void) {{ static volatile int d; stub_note (&d, \"{msg}\"); {ret} }}")
    counts[lib] = counts.get(lib, 0) + 1
open(out, "w").write("\n".join(o) + "\n")
for lib in sorted(counts): print(f"   stubs: {counts[lib]:4d} {lib}")
total = sum(1 for _ in decl)
print(f"   declared entry points {total}, implemented {total - len(missing)}, stubbed {len(missing)}" + (f" ({len(noproto)} without an upstream prototype)" if noproto else ""))
