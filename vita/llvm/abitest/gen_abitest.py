for name, sig in SIGS: I.append(f"  public abstract double {name}<T>(T t, {params(sig)});")
I.append("}")
I.append("public static class IS {")
for name, sig in SIGS:
    I.append(f"  [MethodImpl(MethodImplOptions.NoInlining)] public static double {name}({params(sig)}) => {checksum_expr(sig)};")
I.append("}")
# interp-side caller: through interfaces, virtuals, GVMs, gsharedvt, delegates (all AOT targets); returns failures, logs via callback
I.append("public static class IRun {")
I.append("  public static int RunAll(double[] V, IFoo f, IFoo fm, VBase v, IGv g, GsBase gs, Delegate[] dl, Action<string, bool, double, double> log) {")
I.append("    int fails = 0; double r, e;")
for si, (name, sig) in enumerate(SIGS):
    e = expected(sig); a = build_args(sig)
    def chk(label, expr, extra=0.0):
        I.append(f"    r = {expr}; e = {e + extra!r}; if (Math.Abs(r - e) > 0.25) fails++; log(\"I:{label}:{name}\", Math.Abs(r - e) <= 0.25, r, e);")
    chk("iface", f"f.{name}({a})")
    chk("ifaceM", f"fm.{name}({a})")
    chk("virt", f"v.{name}({a})")
    chk("gvm", f"g.{name}<string>(\"abc\", {a})", 1000.0 * len("String"))
    chk("gvm2", f"g.{name}<System.Text.StringBuilder>(new System.Text.StringBuilder(), {a})", 1000.0 * len("StringBuilder"))
    chk("gsvt", f"gs.{name}<V2>(new V2 {{ F0 = 3, F1 = 4 }}, {a})", 7000.0)
    chk("dlg-static", f"((D_{name})dl[{si * 3 + 0}])({a})")
    chk("dlg-inst", f"((D_{name})dl[{si * 3 + 1}])({a})")
    chk("dlg-mono", f"((D_{name})dl[{si * 3 + 2}])({a})")
I.append("    return fails;\n  }\n}")
I.append("}")
os.makedirs(os.path.join(OUT, "HelloInterp"), exist_ok=True)
open(os.path.join(OUT, "HelloInterp", "InterpWork.cs"), "w").write("\n".join(I) + "\n")

