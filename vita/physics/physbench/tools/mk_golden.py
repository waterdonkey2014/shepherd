#!/usr/bin/env python3
"""mk_golden.py -- turns the T1 golden records (vita/physics/tests/golden/<name>.txt, synthetic scenes, tracked) into a C
header of raw words, so PhysBench can compare a device run record by record (bit-exact, or max ulp + first difference).
Ours. Usage: mk_golden.py <golden_dir> <out.h>
Record layout in the blob: tag, a, b, n, then n words (the golden files' "TAG a b | hex words | decimals" lines)."""
import os
import struct
import sys

ORDER = ["fall_boxes", "stack_boxes", "chain_bowl", "kinematic_sweep", "topdown_slide", "sensor_sequence", "raycasts", "crowd"]


def tag_word(t):
    b = t.encode("ascii")
    assert len(b) == 4, t
    return struct.unpack("<I", b)[0]


def main():
    gdir, out = sys.argv[1], sys.argv[2]
    words, index, total_rec = [], [], 0
    for name in ORDER:
        path = os.path.join(gdir, name + ".txt")
        off, nrec = len(words), 0
        with open(path) as f:
            for line in f:
                if line.startswith("#") or line.startswith("hash") or not line.strip():
                    continue
                head, hexw = line.split("|")[0].split(), line.split("|")[1].split()
                tag, a, b = head[0], int(head[1]), int(head[2])
                words += [tag_word(tag), a & 0xFFFFFFFF, b & 0xFFFFFFFF, len(hexw)] + [int(w, 16) for w in hexw]
                nrec += 1
        index.append((name, off, len(words) - off, nrec))
        total_rec += nrec
    with open(out, "w") as f:
        f.write("/* generated by physbench/tools/mk_golden.py from vita/physics/tests/golden/<name>.txt -- do not edit.\n"
                " * Synthetic T1 scenes only. Per record: tag, a, b, n, n words. */\n")
        f.write("#define PB_T1G_N %d\n#define PB_T1G_RECORDS %d\n" % (len(index), total_rec))
        f.write("static const uint32_t k_pb_t1g_words[%d] = {\n" % len(words))
        for i in range(0, len(words), 8):
            f.write("    " + ", ".join("0x%08xu" % w for w in words[i:i + 8]) + ",\n")
        f.write("};\n")
        f.write("static const struct { const char *name; uint32_t off, nwords, nrec; } k_pb_t1g[PB_T1G_N] = {\n")
        for name, off, n, nrec in index:
            f.write('    {"%s", %d, %d, %d},\n' % (name, off, n, nrec))
        f.write("};\n")
    print("mk_golden: %d scenarios, %d records, %d words -> %s" % (len(index), total_rec, len(words), out))


if __name__ == "__main__":
    main()
