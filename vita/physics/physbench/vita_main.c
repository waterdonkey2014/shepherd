/* Shepherd PhysBench (SHPD00012) -- the physics plan's Stage 0 device micro-benchmark (physics-plan.md D4 / section 6.1).
 * Ours; synthetic scenes only, no game code or data. SILENT (no audio), no network, no GPU.
 * Writes ux0:data/shepherd/physbench.txt (one open/append/close per line, so a crash or freeze still leaves the log up to
 * the failing case) and keeps the previous run as physbench.prev.txt.
 *   1. environment: model, FPSCR at entry, clocks, PSVshell presence, the Mac reference's identity (source sha)
 *   2. T1: the 8 determinism scenarios vs the Mac goldens (bit-exact, or max ulp and the first differing record)
 *   3. per CPU clock (444, then 333, then 500 only if PSVshell is listed in tai config.txt and the owner has not opted out):
 *      STEP / B2 / CALL / ASTAR / FJ / NP / MW (pb_bench.h), each line with the Mac reference and the ratio
 *   4. clocks restored to what they were at launch (logged); SUMMARY lines; START exits (auto exit after 120 s)
 * Clocks (2026-10-13, every Shepherd Vita app): 444/222/222/166 (ARM/bus/GPU/crossbar) are set at start, before anything is
 * measured (CLK start line), and the clocks are logged again at the end (CLK end) before the launch values are restored; the
 * passes then change only the ARM clock (bus 222, GPU 222 / xbar 166 throughout).
 * Every clock change is logged with its return code and the clock read back. Holding START skips what is left.
 */
#include <psp2/ctrl.h>
#include <psp2/io/fcntl.h>
#include <psp2/io/stat.h>
#include <psp2/kernel/clib.h>
#include <psp2/kernel/cpu.h>
#include <psp2/kernel/processmgr.h>
#include <psp2/kernel/sysmem.h>
#include <psp2/kernel/threadmgr.h>
#include <psp2/power.h>
#include <stdarg.h>
#include <stdio.h>
#include <string.h>

#include "debugScreen.h"
#include "mac_ref.h"   /* generated by physbench_mac (build.sh), keyed by the sources' sha */
#include "pb_bench.h"
#include "pb_plat.h"
#include "sp_t1.h"

#ifndef PB_SRC_SHA
#define PB_SRC_SHA "unknown"
#endif

unsigned int _newlib_heap_size_user = 48u * 1024u * 1024u;
const SceSize sceUserMainThreadStackSize = 1024 * 1024;

#define OUT_DIR "ux0:data/shepherd"
#define LOG_PATH OUT_DIR "/physbench.txt"
#define PREV_PATH OUT_DIR "/physbench.prev.txt"
#define NO500_PATH OUT_DIR "/physbench-no500"

static int g_screen, g_stop;
static int g_ref_valid;

static void log_raw(const char *line, int truncate)
{
    SceUID fd = sceIoOpen(LOG_PATH, SCE_O_WRONLY | SCE_O_CREAT | (truncate ? SCE_O_TRUNC : SCE_O_APPEND), 0777);
    if (fd >= 0) { sceIoWrite(fd, line, strlen(line)); sceIoWrite(fd, "\n", 1); sceIoClose(fd); }
    sceClibPrintf("%s\n", line);
    if (g_screen) { psvDebugScreenPuts(line); psvDebugScreenPuts("\n"); }
}
static void log_line(const char *line) { log_raw(line, 0); }
static void logf_(const char *fmt, ...)
{
    char buf[600];
    va_list ap;
    va_start(ap, fmt);
    vsnprintf(buf, sizeof buf, fmt, ap);
    va_end(ap);
    log_raw(buf, 0);
}

static int32_t stop_check(void)
{
    if (!g_stop) {
        SceCtrlData pad;
        memset(&pad, 0, sizeof pad);
        sceCtrlPeekBufferPositive(0, &pad, 1);
        if (pad.buttons & SCE_CTRL_START) { g_stop = 1; log_line("STOP: START pressed -- skipping the remaining cases"); }
    }
    return g_stop;
}

static int32_t mac_ref(const char *key, double *v, uint64_t *check, int32_t *has_check)
{
    for (int i = 0; i < PB_MAC_REF_N; ++i)
        if (!strcmp(PB_MAC_REF[i].key, key)) {
            *v = g_ref_valid ? PB_MAC_REF[i].v : 0.0;   /* no ratios against a reference built from other sources */
            *check = PB_MAC_REF[i].check;
            *has_check = PB_MAC_REF[i].has_check;
            return 1;
        }
    return 0;
}

static void log_clocks(const char *when)
{
    logf_("CLK %s: arm %d MHz, bus %d, gpu %d, gpu xbar %d", when, scePowerGetArmClockFrequency(), scePowerGetBusClockFrequency(),
          scePowerGetGpuClockFrequency(), scePowerGetGpuXbarClockFrequency());
}

/* sets the ARM clock (bus at 222 throughout), logs the request, the return codes and the clocks read back */
static int set_arm(int mhz)
{
    int a0 = scePowerGetArmClockFrequency(), b0 = scePowerGetBusClockFrequency();
    int ra = scePowerSetArmClockFrequency(mhz);
    int rb = scePowerSetBusClockFrequency(222);
    sceKernelDelayThread(250 * 1000);
    int a = scePowerGetArmClockFrequency(), b = scePowerGetBusClockFrequency();
    logf_("CLK set arm %d MHz (rc 0x%08X), bus 222 MHz (rc 0x%08X): arm %d -> %d, bus %d -> %d%s", mhz, (unsigned)ra, (unsigned)rb,
          a0, a, b0, b, a == mhz ? "" : "  <-- NOT the requested clock");
    return a;
}

/* PSVshell listed (not commented out) in a tai config.txt */
static int psvshell_listed(const char *path)
{
    SceUID fd = sceIoOpen(path, SCE_O_RDONLY, 0);
    if (fd < 0) return 0;
    static char buf[32 * 1024];
    int n = sceIoRead(fd, buf, sizeof buf - 1);
    sceIoClose(fd);
    if (n <= 0) return 0;
    buf[n] = 0;
    int found = 0;
    for (char *line = buf; line && *line;) {
        char *nl = strchr(line, '\n');
        if (nl) *nl = 0;
        char *p = line;
        while (*p == ' ' || *p == '\t') ++p;
        if (*p != '#') {
            for (char *q = p; *q; ++q) {
                char l[9];
                int k;
                for (k = 0; k < 8 && q[k]; ++k) l[k] = (char)(q[k] >= 'A' && q[k] <= 'Z' ? q[k] + 32 : q[k]);
                l[k] = 0;
                if (!strcmp(l, "psvshell")) { found = 1; logf_("ENV %s: %s", path, p); break; }
            }
        }
        line = nl ? nl + 1 : NULL;
    }
    return found;
}

static int file_exists(const char *path)
{
    SceIoStat st;
    memset(&st, 0, sizeof st);
    return sceIoGetstat(path, &st) >= 0;
}

static pb_results g_res[3];

static void run_pass(int target, int pass)
{
    char tag[8];
    int got = set_arm(target);
    if (got != target && target == 500) { logf_("PASS 500 SKIPPED: the clock read back %d MHz, not 500", got); return; }
    snprintf(tag, sizeof tag, "%d", got);
    logf_("=== PASS %s MHz%s ===", tag, got == target ? "" : " (SUSPECT: not the requested clock)");
    pb_host h;
    memset(&h, 0, sizeof h);
    h.log = log_line;
    h.ref = mac_ref;
    h.stop = stop_check;
    h.tag = tag;
    h.workers = 2;
    h.fpscr = pb_fpscr_get();
    pb_results *R = &g_res[pass];
    R->n = 0;
    if (!stop_check()) pb_bench_scenes(&h, R);
    log_clocks("after STEP");
    if (!stop_check()) pb_bench_b2(&h, R);
    if (!stop_check()) pb_bench_calls(&h, R);
    if (!stop_check()) pb_bench_astar(&h, R);
    log_clocks("after ASTAR");
    if (!stop_check()) pb_bench_threads(&h, R);
    log_clocks("after threads");
    pb_bench_summary(&h, R);
}

int main(void)
{
    uint32_t fpscr0 = pb_fpscr_get();   /* before anything touches the VFP state */
    sceIoMkdir("ux0:data", 0777);
    sceIoMkdir(OUT_DIR, 0777);
    sceIoRemove(PREV_PATH);              /* keep the previous run's log: it may be the only record of a crash */
    sceIoRename(LOG_PATH, PREV_PATH);
    log_raw("=== Shepherd PhysBench (SHPD00012) " PB_BENCH_VERSION " -- Box2D 2.3.1 core cost on this Vita; synthetic scenes; "
            "silent ===", 1);
    g_screen = psvDebugScreenInit() >= 0;
    /* clocks first: the launch values (restored at the end), then 444/222/222/166 for everything below */
    int c_arm = scePowerGetArmClockFrequency(), c_bus = scePowerGetBusClockFrequency();
    int c_gpu = scePowerGetGpuClockFrequency(), c_xbar = scePowerGetGpuXbarClockFrequency();
    log_clocks("at launch");
    {
        int ra = scePowerSetArmClockFrequency(444), rb = scePowerSetBusClockFrequency(222);
        int rg = scePowerSetGpuClockFrequency(222), rx = scePowerSetGpuXbarClockFrequency(166);
        sceKernelDelayThread(250 * 1000);
        logf_("CLK set 444/222/222/166 at start: rc arm 0x%08X bus 0x%08X gpu 0x%08X xbar 0x%08X", (unsigned)ra, (unsigned)rb,
              (unsigned)rg, (unsigned)rx);
        log_clocks("start");
    }
    log_line("Log: " LOG_PATH ". Takes about 1-3 minutes; hold START to stop early. Clocks are restored at the end.");
    logf_("ENV PSTV %d, model 0x%08X", sceKernelIsPSVitaTV(), (unsigned)sceKernelGetModel());
    logf_("ENV FPSCR at entry 0x%08lx: FZ=%lu DN=%lu RMode=%lu (IEEE = FZ 0, DN 0, RMode 0)", (unsigned long)fpscr0,
          (unsigned long)((fpscr0 >> 24) & 1), (unsigned long)((fpscr0 >> 25) & 1), (unsigned long)((fpscr0 >> 22) & 3));
    {
        SceKernelFreeMemorySizeInfo fi;
        memset(&fi, 0, sizeof fi);
        fi.size = sizeof fi;
        sceKernelGetFreeMemorySize(&fi);
        logf_("ENV free memory: user %.1f MiB, cdram %.1f MiB, phycont %.1f MiB (newlib heap 48 MiB reserved)",
              fi.size_user / 1048576.0, fi.size_cdram / 1048576.0, fi.size_phycont / 1048576.0);
    }
    SceUID self = sceKernelGetThreadId();
    int aff0 = sceKernelGetThreadCpuAffinityMask(self);
    int arc = sceKernelChangeThreadCpuAffinityMask(self, SCE_KERNEL_CPU_MASK_USER_0);
    sceKernelDelayThread(1000);
    logf_("ENV main thread affinity 0x%X -> USER_0 (rc 0x%08X, now 0x%X); workers go to USER_1 / USER_2", aff0, (unsigned)arc,
          sceKernelGetThreadCpuAffinityMask(self));
    g_ref_valid = strcmp(PB_SRC_SHA, PB_MAC_REF_SHA) == 0 && strcmp(PB_MAC_REF_VERSION, PB_BENCH_VERSION) == 0;
    logf_("ENV mac reference: %s (%s, %d passes, deterministic %d) sources %s vs this build %s -> %s", PB_MAC_REF_MACHINE,
          PB_MAC_REF_WHEN, PB_MAC_REF_PASSES, PB_MAC_REF_DETERMINISTIC, PB_MAC_REF_SHA, PB_SRC_SHA,
          g_ref_valid ? "match (ratios valid)" : "MISMATCH (no ratios; hashes still compared)");
    int shell = psvshell_listed("ur0:tai/config.txt") | psvshell_listed("ux0:tai/config.txt");
    int no500 = file_exists(NO500_PATH);
    logf_("ENV PSVshell %s in tai config.txt; 500 MHz pass: %s", shell ? "listed" : "not listed",
          !shell ? "skipped (needs PSVshell, which Shepherd never installs)" : no500 ? "skipped (" NO500_PATH " exists)" : "will be tried");

    pb_host h0;
    memset(&h0, 0, sizeof h0);
    h0.log = log_line;
    h0.ref = mac_ref;
    h0.stop = stop_check;
    h0.tag = "-";
    h0.workers = 2;
    h0.fpscr = pb_fpscr_get();
    pb_bench_header(&h0);
    set_arm(444);
    static pb_results t1r;
    h0.tag = "444";
    int32_t ex = pb_bench_t1(&h0, &t1r);

    run_pass(444, 0);
    if (!stop_check()) run_pass(333, 1);
    if (!stop_check() && shell && !no500) run_pass(500, 2);

    log_clocks("end");
    int ra = scePowerSetArmClockFrequency(c_arm), rb = scePowerSetBusClockFrequency(c_bus);
    int rg = scePowerSetGpuClockFrequency(c_gpu), rx = scePowerSetGpuXbarClockFrequency(c_xbar);
    sceKernelDelayThread(200 * 1000);
    logf_("CLK restored to launch clocks arm %d (rc 0x%08X), bus %d (rc 0x%08X), gpu %d (rc 0x%08X), xbar %d (rc 0x%08X): now arm %d, bus %d, "
          "gpu %d, xbar %d", c_arm, (unsigned)ra, c_bus, (unsigned)rb, c_gpu, (unsigned)rg, c_xbar, (unsigned)rx,
          scePowerGetArmClockFrequency(), scePowerGetBusClockFrequency(), scePowerGetGpuClockFrequency(),
          scePowerGetGpuXbarClockFrequency());
    logf_("T1 RESULT %ld/%ld bit-exact vs the Mac goldens (FPSCR at entry 0x%08lx)", (long)ex, (long)sp_t1_count(),
          (unsigned long)fpscr0);
    logf_("DONE%s -- send %s back (and %s if a run ever stops halfway). Press START to exit.", g_stop ? " (stopped early)" : "",
          LOG_PATH, PREV_PATH);
    g_stop = 0;
    sceKernelDelayThread(500 * 1000);
    SceCtrlData pad;
    for (int i = 0; i < 1200; ++i) {
        memset(&pad, 0, sizeof pad);
        sceCtrlPeekBufferPositive(0, &pad, 1);
        if (pad.buttons & SCE_CTRL_START) break;
        sceKernelDelayThread(100 * 1000);
    }
    sceKernelExitProcess(0);
    return 0;
}
