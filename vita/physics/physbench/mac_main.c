/* mac_main.c -- PhysBench's Mac counterpart (ours): runs pb_bench.c's cases, the same source the Vita eboot runs, and
 * writes the reference the VPK compares itself with (out/mac_ref.h) plus a readable table.
 *   physbench_mac [--quick] [--passes N] [--sections t1,step,b2,call,astar,threads] [--ref <mac_ref.h> --sha <sources sha>
 *                 --machine <cpu>] [--report <file>]
 * Timings are the minimum over N passes (default 5); every hash / count must be identical in every pass.
 * Silent; writes only the files named on the command line. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>
#include <pthread.h>

#include "pb_bench.h"
#include "pb_plat.h"
#include "sp_t1.h"

static FILE *g_report;
static int g_echo = 1;

static void log_line(const char *l)
{
    if (g_echo) { printf("%s\n", l); fflush(stdout); }
    if (g_report) fprintf(g_report, "%s\n", l);
}

int main(int argc, char **argv)
{
    const char *ref = NULL, *sha = "unknown", *machine = "unknown", *report = NULL, *sections = "t1,step,b2,call,astar,threads";
    int passes = 5, quick = 0;
    for (int i = 1; i < argc; ++i) {
        if (!strcmp(argv[i], "--quick")) quick = 1;
        else if (!strcmp(argv[i], "--passes") && i + 1 < argc) passes = atoi(argv[++i]);
        else if (!strcmp(argv[i], "--ref") && i + 1 < argc) ref = argv[++i];
        else if (!strcmp(argv[i], "--sha") && i + 1 < argc) sha = argv[++i];
        else if (!strcmp(argv[i], "--machine") && i + 1 < argc) machine = argv[++i];
        else if (!strcmp(argv[i], "--report") && i + 1 < argc) report = argv[++i];
        else if (!strcmp(argv[i], "--sections") && i + 1 < argc) sections = argv[++i];
        else { fprintf(stderr, "usage: %s [--quick] [--passes N] [--sections list] [--ref out.h --sha S --machine M] [--report file]\n", argv[0]); return 2; }
    }
    if (quick) passes = 1;
    if (passes < 1) passes = 1;
    pthread_set_qos_class_self_np(QOS_CLASS_USER_INTERACTIVE, 0);
    static pb_results all[8], best;
    pb_host h;
    memset(&h, 0, sizeof h);
    h.log = log_line;
    h.tag = "mac";
    h.workers = 2;
    h.fpscr = pb_fpscr_get();
    h.quick = quick;
    int bad = 0;
    for (int p = 0; p < passes && p < 8; ++p) {
        if (p == passes - 1 && report) g_report = fopen(report, "w");   /* the readable report keeps the last pass's log */
        g_echo = p == 0 || p == passes - 1;
        char line[160];
        snprintf(line, sizeof line, "=== physbench mac pass %d/%d (sources %s) ===", p + 1, passes, sha);
        log_line(line);
        if (p == 0 || p == passes - 1) pb_bench_header(&h);
        pb_results *R = &all[p];
        R->n = 0;
        if (strstr(sections, "t1") && pb_bench_t1(&h, R) != sp_t1_count()) bad = 1;
        if (strstr(sections, "step")) pb_bench_scenes(&h, R);
        if (strstr(sections, "b2")) pb_bench_b2(&h, R);
        if (strstr(sections, "call")) pb_bench_calls(&h, R);
        if (strstr(sections, "astar")) pb_bench_astar(&h, R);
        if (strstr(sections, "threads")) pb_bench_threads(&h, R);
        pb_bench_summary(&h, R);
    }
    /* best of N: minimum time per key; checks must agree in every pass */
    best = all[0];
    for (int p = 1; p < passes && p < 8; ++p)
        for (int i = 0; i < best.n; ++i) {
            const pb_res *r = pb_find(&all[p], best.r[i].key);
            if (!r) continue;
            if (r->has_check && r->check != best.r[i].check) {
                fprintf(stderr, "NONDETERMINISTIC %s: pass 1 %016llx, pass %d %016llx\n", best.r[i].key,
                        (unsigned long long)best.r[i].check, p + 1, (unsigned long long)r->check);
                bad = 1;
            }
            if (best.r[i].unit[0] && r->v < best.r[i].v) best.r[i].v = r->v;
        }
    if (g_report) {
        fprintf(g_report, "\n# best of %d passes (minimum per timing; checks identical in every pass: %s)\n", passes, bad ? "NO" : "yes");
        for (int i = 0; i < best.n; ++i)
            if (best.r[i].has_check)
                fprintf(g_report, "%-34s %12.3f %-2s check %016llx\n", best.r[i].key, best.r[i].v, best.r[i].unit,
                        (unsigned long long)best.r[i].check);
            else fprintf(g_report, "%-34s %12.3f %-2s\n", best.r[i].key, best.r[i].v, best.r[i].unit);
        fclose(g_report);
        g_report = NULL;
    }
    if (ref) {
        FILE *f = fopen(ref, "w");
        if (!f) { perror(ref); return 1; }
        time_t t = time(NULL);
        char when[32];
        strftime(when, sizeof when, "%Y-%m-%d %H:%M:%S", localtime(&t));
        fprintf(f, "/* generated by physbench_mac -- do not edit. Timings and hashes of synthetic scenes only (no game data). */\n");
        fprintf(f, "#define PB_MAC_REF_AVAILABLE 1\n#define PB_MAC_REF_SHA \"%s\"\n#define PB_MAC_REF_MACHINE \"%s\"\n", sha, machine);
        fprintf(f, "#define PB_MAC_REF_WHEN \"%s\"\n#define PB_MAC_REF_VERSION \"%s\"\n#define PB_MAC_REF_PASSES %d\n", when,
                PB_BENCH_VERSION, passes);
        fprintf(f, "#define PB_MAC_REF_DETERMINISTIC %d\n", bad ? 0 : 1);
        fprintf(f, "static const struct pb_mac_ref_row { const char *key; double v; unsigned long long check; int has_check; } "
                   "PB_MAC_REF[] = {\n");
        for (int i = 0; i < best.n; ++i)
            fprintf(f, "    {\"%s\", %.6f, 0x%016llxull, %d},\n", best.r[i].key, best.r[i].v, (unsigned long long)best.r[i].check,
                    (int)best.r[i].has_check);
        fprintf(f, "};\n#define PB_MAC_REF_N %d\n", best.n);
        fclose(f);
    }
    return bad ? 3 : 0;
}
