#!/usr/bin/env python3
"""DIAG-ONLY (devfail1, "Shepherd Menu Diag" SHPD00016; vita/shepherd/build.sh with SHEPHERD_DIAG=1 runs this, normal builds never do).

Counts managed->native calls without touching the runtime, the shim or the AOT code: every P/Invoke target in the static table and
every icall the AOT code calls directly is linked with ld --wrap, so references from OTHER objects (the AOT images' direct calls,
the static P/Invoke table the interpreter binds through) reach a small static thunk first:
    count += 1; last = <index>; tail-jump to the real function (registers and stack untouched apart from r12/ip)
The thunks are plain static code in the eboot (no generated code at run time, no executable memory). A few P/Invokes get C wrappers
that also count files/bytes (SystemNative_Open/Read/PRead/Write/PWrite), and sceKernelCreateThread is wrapped to count threads.
Calls a function makes to itself / within its own object are not wrapped (ld --wrap semantics) and are not counted.

usage: gen_diag_wraps.py <static-symbols.txt> <aot-undefined.txt> <out dir>
writes: <out>/diag_wraps.S (generic thunks), <out>/diag_wraps.c (name tables + C wrappers), <out>/wraps.rsp (-Wl,--wrap=... lines)
"""
import os
import sys

static_syms, aot_undef, out = sys.argv[1:4]
pinv = [l.strip() for l in open(static_syms) if l.strip()]
# (kit #4: GC.Collect's icall is already wrapped by host.c's governor, so it gets no counting thunk)
icall = sorted({l.strip() for l in open(aot_undef) if l.strip().startswith('ves_icall_')} - set(pinv) - {'ves_icall_System_GC_InternalCollect'})

IO = {
    'SystemNative_Open': ('intptr_t', 'const char *path, int32_t flags, int32_t mode', 'path, flags, mode',
                          'if (r >= 0) { shp_diag_files_opened++; note_path (path); } else shp_diag_open_failed++;'),
    'SystemNative_Read': ('int32_t', 'intptr_t fd, void *buffer, int32_t size', 'fd, buffer, size',
                          'shp_diag_reads++; if (r > 0) shp_diag_bytes_read += (unsigned) r;'),
    'SystemNative_PRead': ('int32_t', 'intptr_t fd, void *buffer, int32_t size, int64_t offset', 'fd, buffer, size, offset',
                           'shp_diag_reads++; if (r > 0) shp_diag_bytes_read += (unsigned) r;'),
    'SystemNative_Write': ('int32_t', 'intptr_t fd, const void *buffer, int32_t size', 'fd, buffer, size',
                           'shp_diag_writes++; if (r > 0) shp_diag_bytes_written += (unsigned) r;'),
    'SystemNative_PWrite': ('int32_t', 'intptr_t fd, void *buffer, int32_t size, int64_t offset', 'fd, buffer, size, offset',
                            'shp_diag_writes++; if (r > 0) shp_diag_bytes_written += (unsigned) r;'),
}

os.makedirs(out, exist_ok=True)
S = ['/* GENERATED by vita/shepherd/diag/gen_diag_wraps.py (DIAG-ONLY): counting thunks, ld --wrap targets */',
     '\t.syntax unified', '\t.arch armv7-a', '\t.thumb']


def thunk(name, idx, counter, last):
    return [f'\t.section .text.__wrap_{name},"ax",%progbits', '\t.align 2', f'\t.global __wrap_{name}', f'\t.type __wrap_{name}, %function',
            '\t.thumb_func', f'__wrap_{name}:', '\tpush {r0, r1}', f'\tldr r0, ={counter}', '\tldr r1, [r0]', '\tadd r1, r1, #1',
            '\tstr r1, [r0]', f'\tldr r0, ={last}', f'\tmovw r1, #{idx}', '\tstr r1, [r0]', '\tpop {r0, r1}', f'\tldr ip, =__real_{name}',
            '\tbx ip', '\t.ltorg', f'\t.size __wrap_{name}, . - __wrap_{name}']


for i, n in enumerate(pinv):
    if n not in IO:
        S += thunk(n, i, 'shp_diag_pinv_calls', 'shp_diag_pinv_last')
for i, n in enumerate(icall):
    S += thunk(n, i, 'shp_diag_icall_calls', 'shp_diag_icall_last')
open(os.path.join(out, 'diag_wraps.S'), 'w').write('\n'.join(S) + '\n')

C = ['/* GENERATED by vita/shepherd/diag/gen_diag_wraps.py (DIAG-ONLY): name tables + the counting C wrappers */',
     '#include <stdint.h>', '#include <string.h>', '#include <psp2/kernel/threadmgr.h>', '#include "shp_diag.h"',
     f'const int shp_diag_pinv_count = {len(pinv)};', 'const char *const shp_diag_pinv_names [] = {']
C += [f'\t"{n}",' for n in pinv] + ['\t0 };', f'const int shp_diag_icall_count = {len(icall)};', 'const char *const shp_diag_icall_names [] = {']
C += [f'\t"{n}",' for n in icall] + ['\t0 };', '',
      'static void note_path (const char *p)',
      '{', '\tsize_t n = p ? strlen (p) : 0;', '\tif (n > sizeof (shp_diag_last_path) - 1) { p += n - (sizeof (shp_diag_last_path) - 1); n = sizeof (shp_diag_last_path) - 1; }',
      '\tif (p) memcpy (shp_diag_last_path, p, n);', '\tshp_diag_last_path [n] = 0;', '}', '']
for n, (ret, params, args, after) in IO.items():
    if n not in pinv:
        continue
    i = pinv.index(n)
    C += [f'extern {ret} __real_{n} ({params});', f'{ret} __wrap_{n} ({params});', f'{ret} __wrap_{n} ({params})', '{',
          f'\tshp_diag_pinv_calls++;', f'\tshp_diag_pinv_last = {i};', f'\t{ret} r = __real_{n} ({args});', f'\t{after}', '\treturn r;', '}', '']
C += ['extern SceUID __real_sceKernelCreateThread (const char *name, SceKernelThreadEntry entry, int prio, SceSize stack, SceUInt attr, int cpu, const SceKernelThreadOptParam *opt);',
      'SceUID __wrap_sceKernelCreateThread (const char *name, SceKernelThreadEntry entry, int prio, SceSize stack, SceUInt attr, int cpu, const SceKernelThreadOptParam *opt);',
      'SceUID __wrap_sceKernelCreateThread (const char *name, SceKernelThreadEntry entry, int prio, SceSize stack, SceUInt attr, int cpu, const SceKernelThreadOptParam *opt)',
      '{', '\tSceUID u = __real_sceKernelCreateThread (name, entry, prio, stack, attr, cpu, opt);',
      '\tunsigned k = shp_diag_threads_created++;', '\tif (k < SHP_DIAG_MAX_THREADS) shp_diag_thread_uids [k] = u;',
      '\tsize_t n = name ? strlen (name) : 0;', '\tif (n > sizeof (shp_diag_last_thread) - 1) n = sizeof (shp_diag_last_thread) - 1;',
      '\tif (name) memcpy (shp_diag_last_thread, name, n);', '\tshp_diag_last_thread [n] = 0;', '\treturn u;', '}']
open(os.path.join(out, 'diag_wraps.c'), 'w').write('\n'.join(C) + '\n')

with open(os.path.join(out, 'wraps.rsp'), 'w') as f:
    for n in pinv + icall + ['sceKernelCreateThread']:
        f.write(f'-Wl,--wrap={n}\n')
print(f'diag wraps: {len(pinv)} P/Invoke targets ({sum(1 for n in IO if n in pinv)} with IO counters), {len(icall)} AOT direct icalls, sceKernelCreateThread')
