#!/usr/bin/env python3
"""Kit #7 tests track (vita/notes/kit7-tests.md "Compiler + instruction differential tests"): the Vita tiers of the IL conformance suite.
Generates the managed half of a vlx-only copy of the hello app (vita/hello, SHPD00005's recipe, built into the work dir, NEVER for the
device): Hello.dll (static full AOT, Mono's ARMv7 backend -- the AOT tier) and HelloInterp.dll (deliberately interpreted -- the
interpreter tier, which runs the game's own DLLs in 00097 / 00098 / 00099 / 00011) both hold the SAME test sources (Mono's mini tests,
FpMode.cs, and random float programs from fuzz.py), each wrapped in its own namespace, plus a generated table that calls every test
directly (no reflection, so the AOT tier really runs AOT code). Hello's Main runs both tables and logs one line per test through the
host (M<n> lines in ux0:data/shepherd/hello.txt): "<tier>\t<file>\t<class>.<method>\t<value>".
  hello-gen.py <managed dir> <test .cs files...>"""
import sys, os, re
out, files = sys.argv[1], sorted(sys.argv[2:], key=os.path.basename)   # (the table in file-name order: the 2026-10-20 run's order)
os.makedirs(os.path.join(out, "HelloInterp"), exist_ok=True)
TEST = re.compile(r"\b(?:public\s+|internal\s+|private\s+)?static\s+int\s+((?:test|fp)_\w+)\s*\(\s*\)")
CLASS = re.compile(r"\b(?:public\s+|internal\s+)?(?:static\s+|unsafe\s+|partial\s+)*(?:class|struct)\s+(\w+)")

def wrap(path, ns):
    src = open(path, encoding="utf-8", errors="replace").read()
    lines = src.split("\n"); i = 0
    while i < len(lines) and (lines[i].startswith("using ") or lines[i].strip() == "" or lines[i].lstrip().startswith("//") or lines[i].startswith("#")): i += 1
    head, body = "\n".join(lines[:i]), "\n".join(lines[i:])
    body = re.sub(r"\bpublic\s+static\s+int\s+Main\s*\(", "public static int MainUnused(", body)   # (one entry point per assembly)
    return head + f"\nnamespace {ns} {{\n" + body + "\n}\n", body

def tests_of(body):
    found = []; cls = None; depth = 0; stack = []
    # (kit #7 review fix: tests commented out in Mono's sources -- /* ... */ blocks, // lines: basic-long's test_0_conv_from_r4 / _r8,
    # basic-float's test_0_long_to_double_conversion -- are not tests; the 2026-10-20 run's table left them out by hand)
    body = re.sub(r"/\*.*?\*/", lambda m: "\n" * m.group(0).count("\n"), body, flags=re.S)
    for line in body.split("\n"):
        if line.lstrip().startswith("//"): continue
        m = CLASS.search(line)
        if m and "{" in line or (m and not line.strip().endswith(";")): stack.append((m.group(1), depth))
        t = TEST.search(line)
        if t and stack: found.append((stack[-1][0], t.group(1)))
        depth += line.count("{") - line.count("}")
        while stack and depth <= stack[-1][1] and "}" in line: stack.pop()
    return found

for tier, sub in (("aot", ""), ("interp", "HelloInterp")):
    calls = []
    for f in files:
        base = os.path.splitext(os.path.basename(f))[0]; ns = "Conf_" + re.sub(r"\W", "_", base) + ("_I" if tier == "interp" else "")
        text, body = wrap(f, ns)
        open(os.path.join(out, sub, base + ".cs"), "w").write(text)
        for cls, m in tests_of(body): calls.append((base, ns, cls, m))
    tab = ["using System;", "namespace ShepherdConf {", f"  public static class Table{'Interp' if tier == 'interp' else 'Aot'} {{",
           "    public static int Run(Action<string> log) { int n = 0; string v;"]
    for base, ns, cls, m in calls:
        tab.append(f"      try {{ v = {ns}.{cls}.{m}().ToString(); }} catch (Exception e) {{ v = \"EXC:\" + e.GetType().Name; }} log(\"{tier}\\t{base}\\t{cls}.{m}\\t\" + v); n++;")
    tab += ["      return n; }", "  }", "}"]
    open(os.path.join(out, sub, f"Table{'Interp' if tier == 'interp' else 'Aot'}.cs"), "w").write("\n".join(tab) + "\n")
    print(f"{tier}: {len(calls)} tests from {len(files)} files")

open(os.path.join(out, "Hello.cs"), "w").write('''// GENERATED by vita/tests/il/hello-gen.py (kit #7 tests track): the IL conformance suite's Vita-tier driver (vlx only, never for the device).
using System;
using System.Runtime.InteropServices;
namespace ShepherdVita
{
    public static class Hello
    {
        [DllImport("__Internal", EntryPoint = "shepherd_hello_log")]
        static extern void HostLog(int step, [MarshalAs(UnmanagedType.LPUTF8Str)] string msg);
        public static int Main(string[] args)
        {
            HostLog(1, "CONF begin (kit #7 IL conformance: aot = this image, interp = HelloInterp.dll)");
            int a = ShepherdConf.TableAot.Run(s => HostLog(50, s));
            int b = ShepherdConf.TableInterp.Run(s => HostLog(51, s));
            HostLog(99, "CONF end: " + a + " aot tests, " + b + " interp tests");
            return 0;
        }
    }
}
''')
