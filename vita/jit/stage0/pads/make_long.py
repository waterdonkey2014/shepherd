#!/usr/bin/env python3
"""Kit #7 JIT stage 0: the long-session pad script for the code-cache census (vita/notes/kit7-jit.md).
Every frame is m+N (after the Main Menu scene's first arrival: Diag/MenuClock.cs), so the script lands on the same screens whatever the
execution mode's speed. Pad semantics as the kit #4 intro pads (vita/tools/kit4-intro/pads/intro-explore.txt: the pad is a DualShock-4
joystick to Rewired; menu / dialogue cross, movement the left stick, attack square, dodge circle, heavy attack r).
Route (everything the Mac can reach today without a save past the intro):
  1. the Main Menu tour: DLC, Settings (every tab, then close: the game writes its settings into the sandbox copy), Credits, Roadmap,
     Achievements -- open, look, close;
  2. Play -> empty slot -> New Game -> the two quotes -> Game Biome Intro: the dialogue, then a long move / attack / dodge / heavy-attack loop;
  3. the pause menu (look around, close), the loop again, then pause -> Main Menu -> Accept (the scene reload back to the Main Menu);
  4. Play -> slot -> New Game a SECOND time -> the intro again, a shorter loop (what a repeat visit adds to the code cache).
usage: make_long.py [loop_frames] [loop2_frames] > long-session.txt"""
import sys

LOOP = int(sys.argv[1]) if len(sys.argv) > 1 else 9000
LOOP2 = int(sys.argv[2]) if len(sys.argv) > 2 else 3000
out = []
def ev(f, b, hold=None, note=None):
    out.append(f"m+{f}:{b}" + (f":{hold}" if hold else "") + (f"    # {note}" if note else ""))

def tour(t):
    ev(t + 0, "down", note="Play -> DLC"); ev(t + 30, "cross", note="open DLC"); ev(t + 200, "circle", note="close DLC")
    ev(t + 300, "down", note="DLC -> Settings"); ev(t + 330, "cross", note="open Settings")
    for i in range(5): ev(t + 420 + 60 * i, "r", note="next tab" if i == 0 else None)
    ev(t + 740, "down"); ev(t + 770, "down"); ev(t + 800, "up"); ev(t + 830, "up")
    for i in range(5): ev(t + 880 + 40 * i, "l")
    ev(t + 1100, "circle", note="close Settings (the game saves settings.json into the sandbox copy)")
    ev(t + 1200, "down", note="Settings -> Credits"); ev(t + 1230, "cross", note="open Credits"); ev(t + 1470, "circle", note="close Credits")
    ev(t + 1570, "down", note="Credits -> Roadmap"); ev(t + 1600, "cross", note="open Roadmap"); ev(t + 1770, "circle")
    ev(t + 1870, "down", note="Roadmap -> Achievements"); ev(t + 1900, "cross", note="open Achievements"); ev(t + 2070, "circle")
    for i in range(5): ev(t + 2170 + 30 * i, "up", note="back to Play" if i == 0 else None)
    return t + 2320

def new_game(t, tag):
    ev(t, "cross", note=f"Play ({tag})"); ev(t + 200, "cross", note="empty slot -> New Game")
    # the QuoteScreen and the intro load: ~1,335 frames from the slot press on the frame clock (jitstudy gain lane: f1600 -> f2935);
    # crosses every 60 frames from +1400 to +1940 advance the intro's dialogue whatever the exact arrival frame
    for i in range(10): ev(t + 200 + 1400 + 60 * i, "cross", note="intro dialogue" if i == 0 else None)
    return t + 200 + 2000

def loop(t, frames):
    dirs = ["lup", "lright", "ldown", "lleft"]
    k = 0
    end = t + frames
    while t + 120 <= end:
        d = dirs[k % 4]
        ev(t, d, 90); ev(t + 20, "square"); ev(t + 50, "square"); ev(t + 75, "circle")
        if k % 3 == 2: ev(t + 95, "r", 20)
        if k % 16 == 7: ev(t + 100, "triangle")
        t += 120; k += 1
    return end

def pause_look(t):
    ev(t, "start", note="pause menu")
    for i in range(4): ev(t + 150 + 100 * i, "down")
    for i in range(4): ev(t + 550 + 100 * i, "up")
    ev(t + 1000, "circle", note="close the pause menu")
    return t + 1100

def pause_to_menu(t):
    ev(t, "start", note="pause -> Main Menu (4 downs from Resume) -> confirm: right (Accept), cross")
    for i in range(4): ev(t + 100 + 50 * i, "down")
    ev(t + 350, "cross"); ev(t + 450, "right"); ev(t + 500, "cross")
    return t + 500 + 1200   # the Main Menu scene reload

t = 244
ev(t, "cross", note='engage "Press Any Button to Start"')
t = tour(t + 250)
t = new_game(t + 100, "1st")
t = loop(t, LOOP // 2)
t = pause_look(t + 60)
t = loop(t, LOOP - LOOP // 2)
t = pause_to_menu(t + 60)
ev(t, "cross", note='engage again if the reloaded menu asks')
t = new_game(t + 300, "2nd: the repeat visit")
t = loop(t, LOOP2)
print(f"# generated by vita/jit/stage0/pads/make_long.py {LOOP} {LOOP2}: ends at m+{t} (stop the run there: SHEPHERD_STOP_AT=m+{t})")
print("\n".join(out))
