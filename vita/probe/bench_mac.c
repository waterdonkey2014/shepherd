/* bench_mac.c -- Mac host for bench.c (the reference side of the V0 CPU calibration).
 * Usage: bench_mac <mac_ref.h out> <bench.c sha256> <machine string> <flags string>
 * Pins nothing (macOS has no hard affinity); runs at default QoS on a P-core in practice. */
#include "bench.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>
#include <pthread.h>

static uint64_t now_us(void) {
  struct timespec ts;
  clock_gettime(CLOCK_MONOTONIC_RAW, &ts);
  return (uint64_t)ts.tv_sec * 1000000u + (uint64_t)(ts.tv_nsec / 1000);
}
static void log_line(const char *l) { printf("%s\n", l); fflush(stdout); }
static int pre(const char *name, char *note, int n) { (void)name; snprintf(note, n, "mac"); return 0; }

int main(int argc, char **argv) {
  if (argc < 5) { fprintf(stderr, "usage: %s out.h sha machine flags\n", argv[0]); return 2; }
  pthread_set_qos_class_self_np(QOS_CLASS_USER_INTERACTIVE, 0); /* keep it on a P-core */
  void *arena = malloc(BENCH_ARENA_BYTES);
  if (!arena) return 1;
  memset(arena, 0, BENCH_ARENA_BYTES);
  bench_host h = {now_us, log_line, pre};
  /* 5 full passes; keep each kernel's minimum so one noisy pass (background load, core placement) can't skew the reference */
  bench_result r[BENCH_MAX_RESULTS], pass[BENCH_MAX_RESULTS];
  int n = 0;
  for (int p = 0; p < 5; p++) {
    int m = bench_run_all(&h, arena, BENCH_ARENA_BYTES, pass, BENCH_MAX_RESULTS);
    if (m <= 0) return 1;
    if (p == 0) { memcpy(r, pass, sizeof pass); n = m; continue; }
    for (int i = 0; i < n; i++) {
      if (pass[i].checksum != r[i].checksum) { fprintf(stderr, "nondeterministic checksum in %s\n", r[i].name); return 3; }
      if (pass[i].min_ms < r[i].min_ms) { r[i].min_ms = pass[i].min_ms; r[i].metric = pass[i].metric; }
    }
  }
  FILE *f = fopen(argv[1], "w");
  if (!f) return 1;
  time_t t = time(NULL);
  char when[32];
  strftime(when, sizeof when, "%Y-%m-%d %H:%M:%S", localtime(&t));
  fprintf(f, "/* generated by bench_mac -- do not edit. Numbers only, no game data. */\n");
  fprintf(f, "#define MAC_REF_AVAILABLE 1\n#define MAC_REF_MACHINE \"%s\"\n#define MAC_REF_WHEN \"%s\"\n", argv[3], when);
  fprintf(f, "#define MAC_REF_BENCH_SHA256 \"%s\"\n#define MAC_REF_FLAGS \"%s\"\n#define MAC_REF_VERSION \"%s\"\n", argv[2], argv[4], BENCH_VERSION);
  fprintf(f, "static const struct { const char *name; double min_ms; double metric; const char *unit; unsigned checksum; } MAC_REF[] = {\n");
  for (int i = 0; i < n; i++)
    fprintf(f, "  {\"%s\", %.6f, %.6f, \"%s\", 0x%08XU},\n", r[i].name, r[i].min_ms, r[i].metric, r[i].unit, (unsigned)r[i].checksum);
  fprintf(f, "};\n#define MAC_REF_N %d\n", n);
  fclose(f);
  free(arena);
  return 0;
}
