#!/bin/zsh
# SHEPHERD-VITA V6 (vita/notes/v6-vita-build.md section 4): the newlib heap's fragmentation term, measured on the Mac.
#   1. builds interpose.dylib (records every malloc-family call) and replay (dlmalloc 2.8.3 on an sbrk-only heap: newlib's
#      shape on the Vita; generated from the runtime fork's public-domain copy with Mono's changes undone)
#   2. runs vita/shepherd/mac-check/run.sh (the Vita host, the full menu boot) with the interposer -> a trace on the build volume
#   3. replays the trace: sbrk high-water vs peak bytes in use
# usage: run.sh [out-dir]   (default ${SHEPHERD_WORK:-$HOME/shepherd-work}/v6b/newlib-frag; the trace is deleted unless KEEP_TRACE=1)
set -euo pipefail
HERE=${0:a:h}
REPO=${HERE:h:h:h:h}
export TMPDIR=${TMPDIR:-${SHEPHERD_WORK:-$HOME/shepherd-work}/tmp}
R=${SHEPHERD_RUNTIME:-${SHEPHERD_WORK:-$HOME/shepherd-work}/runtime}
OUT=${1:-${SHEPHERD_WORK:-$HOME/shepherd-work}/v6b/newlib-frag}
mkdir -p "$OUT"
DL=$R/src/mono/mono/utils/dlmalloc.c
[ -f "$DL" ] || { echo "no $DL (attach the build volume)"; exit 1; }

# dlmalloc-sbrk.c: Mono's header block (mmap-only, mono_valloc, no MORECORE) replaced by an sbrk-only configuration, and
# the blocks Mono compiled out that realloc/calloc need turned back on
python3 - "$DL" "$OUT/dlmalloc-sbrk.c" <<'EOF'
import re, sys
src = open(sys.argv[1]).read()
head = '#include "mono-mmap.h"'
tail = '#include <mono/utils/dlmalloc.h>'
a, b = src.index(head), src.index(tail) + len(tail)
cfg = '''/* generated by vita/v6/tools/newlib-frag/run.sh: sbrk-only, no mmap, no locks (single-threaded replay) */
#define USE_DL_PREFIX 1
#define USE_LOCKS 0
#define HAVE_MORECORE 1
#define MORECORE sim_sbrk
#define MORECORE_CONTIGUOUS 1
#define HAVE_MMAP 0
#define NO_MALLINFO 1
#define MALLOC_FAILURE_ACTION errno = ENOMEM;'''
src = src[:a] + cfg + src[b:]
lines = src.split('\n')
def enable(fn):
    # the '#if 0' right before the first definition of fn
    i = next(k for k, l in enumerate(lines) if re.match(r'^(static )?\w[\w\s\*]*\b' + fn + r'\s*\(', l) and not l.rstrip().endswith(';'))
    j = max(k for k in range(i) if lines[k].strip() == '#if 0')
    lines[j] = '#if 1 /* re-enabled for the replay */'
for fn in ('mmap_resize', 'internal_realloc', 'dlcalloc'):
    enable(fn)
open(sys.argv[2], 'w').write('\n'.join(lines))
EOF

clang -O2 -Wall -dynamiclib -o "$OUT/interpose.dylib" "$HERE/interpose.c"
clang -O2 -w -I"$OUT" -o "$OUT/replay" "$HERE/replay.c"

TRACE=$OUT/trace.bin
rm -f "$TRACE"
echo "newlib-frag: mac-check with the interposer (trace -> $TRACE)"
NEWLIB_FRAG_TRACE=$TRACE MAC_PRELOAD=$OUT/interpose.dylib MAC_OUT=$OUT/mac-check "$REPO/vita/shepherd/mac-check/run.sh" | tail -3
ls -la "$TRACE"
"$OUT/replay" "$TRACE" "mac-check menu boot" | tee "$OUT/replay.txt"
[[ ${KEEP_TRACE:-0} = 1 ]] || rm -f "$TRACE"
