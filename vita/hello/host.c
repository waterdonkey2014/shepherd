static void log_line (const char *line)
{
	pthread_mutex_lock (&log_lock);
	SceUID fd = sceIoOpen (LOG_FILE, SCE_O_WRONLY | SCE_O_CREAT | SCE_O_APPEND, 0777);
	if (fd >= 0) {
		sceIoWrite (fd, line, strlen (line));
		sceIoWrite (fd, "\n", 1);
		sceIoClose (fd);
	}
#ifdef HELLO_DIAG
	g_log_lines++;
#endif
	sceClibPrintf ("%s\n", line);
	if (g_screen) {
		psvDebugScreenPuts (line);
		psvDebugScreenPuts ("\n");
	}
	pthread_mutex_unlock (&log_lock);
}

static void logf_ (const char *fmt, ...)
{
	char buf [768];
	va_list ap;
	va_start (ap, fmt);
	vsnprintf (buf, sizeof (buf), fmt, ap);
	va_end (ap);
	log_line (buf);
}
#define LOG(...) logf_ (__VA_ARGS__)

/* nonblocking: for the fatal/exit paths, which can run on a thread that is inside an arena call (try-lock) */
static void log_mem_ex (const char *when, int nonblocking)
{
	SceKernelFreeMemorySizeInfo fi;
	memset (&fi, 0, sizeof (fi));
	fi.size = sizeof (fi);
	sceKernelGetFreeMemorySize (&fi);
	struct mallinfo mi = mallinfo ();
	MonoVitaArenaStats st;
	if (nonblocking) {
		if (mono_vita_vm_arena_try_get_stats (&st) != 0) {
			LOG ("MEM %s: free user=%u KiB cdram=%u KiB phycont=%u KiB | newlib heap used=%u KiB of %u KiB | mono arena busy (its lock is held)",
			     when, fi.size_user / 1024, fi.size_cdram / 1024, fi.size_phycont / 1024,
			     (unsigned) mi.uordblks / 1024, HELLO_NEWLIB_HEAP / 1024);
			return;
		}
	} else {
		mono_vita_vm_arena_get_stats (&st);
	}
	LOG ("MEM %s: free user=%u KiB cdram=%u KiB phycont=%u KiB | newlib heap used=%u KiB of %u KiB | mono arena used=%u KiB peak=%u KiB of %u KiB, %u extents, exec-refused=%u",
	     when, fi.size_user / 1024, fi.size_cdram / 1024, fi.size_phycont / 1024,
	     (unsigned) mi.uordblks / 1024, HELLO_NEWLIB_HEAP / 1024,
	     (unsigned) (st.used / 1024), (unsigned) (st.peak / 1024), (unsigned) (st.arena_size / 1024), st.free_extents, st.exec_requests);
}
#define log_mem(when) log_mem_ex ((when), 0)

