static void mono_log_cb (const char *domain, const char *level, const char *message, mono_bool fatal, void *user_data)
{
#ifdef HELLO_DIAG
	/* the whole message, in 600-byte pieces (LOG's buffer would cut it at ~760) */
	size_t mlen = message ? strlen (message) : 0;
	for (size_t off = 0; off < mlen || off == 0; off += 600) {
		LOG ("R> [%s %s]%s %.600s", domain ? domain : "mono", level ? level : "", off ? " (cont.)" : "", message ? message + off : "(null)");
		if (!mlen)
			break;
	}
	if (fatal)
		LOG ("FAIL (diag) the runtime stops here: the N> EXC / EXC-FAIL / SUSPEND-STATE lines above (if any) are the diagnostic runtime's details");
#else
	LOG ("R> [%s %s] %s", domain ? domain : "mono", level ? level : "", message);
#endif
	if (fatal) {
		log_mem_ex ("fatal", 1);   /* try-lock: the error may come from inside an arena call */
		LOG ("FAIL runtime fatal error (see the R> line above)");
		/* Mono requires a fatal log handler not to return (after it, g_error spins in for (;;) and g_assert calls
		 * exit (0)). Leave the FAIL line on the debug screen long enough to read, then abort: on the Vita, newlib's
		 * abort() traps, so the system error dialog and a core dump follow. Not a handler of any kind. */
		if (g_screen)
			sceKernelDelayThread (10 * 1000 * 1000);
		abort ();
	}
}

/* g_print/g_printerr text can span many lines (an unhandled exception's ToString is a whole stack trace):
 * log each line on its own, so nothing is lost to the 768-byte line buffer */
static void mono_print_cb (const char *string, mono_bool is_stdout)
{
	const char *prefix = is_stdout ? "R> " : "R!> ";
	if (!is_stdout && strstr (string, "Unhandled Exception:"))
		g_unhandled_printed = 1;
	for (const char *p = string; *p;) {
		const char *nl = strchr (p, '\n');
		size_t n = nl ? (size_t) (nl - p) : strlen (p);
		for (size_t off = 0; off < n; off += 700) {
			size_t chunk = n - off < 700 ? n - off : 700;
			LOG ("%s%.*s", prefix, (int) chunk, p + off);
		}
		p += n + (nl ? 1 : 0);
	}
}

