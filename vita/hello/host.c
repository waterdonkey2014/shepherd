/* ---------------------------------------------------------------- H0: vitasdk's stock sem_post vs the app's corrected one */

/* build.sh links vitasdk's own sem_post.o renamed to shepherd_stock_sem_post (libpthread.a, objcopy --redefine-sym), next to
 * the corrected sem_post the app uses (vita/runtime/system-native/vita_pthread_fix.c). Post with nobody waiting, take it back
 * with a wait that does not block, then a 200 ms timed wait with nothing posted MUST time out; the stock sem_post leaves a
 * stale count in the kernel semaphore and that wait returns at once (the cause of the coop GC's "Cannot read suspend state"). */
#include <semaphore.h>
#include <errno.h>
#include <time.h>
extern int shepherd_stock_sem_post (sem_t *sem);
static const char *sem_selftest (int (*post) (sem_t *), char *buf, size_t n)
{
	sem_t s;
	if (sem_init (&s, 0, 0) != 0)
		return "sem_init failed";
	post (&s);
	sem_wait (&s);
	struct timespec ts;
	clock_gettime (CLOCK_REALTIME, &ts);
	ts.tv_nsec += 200 * 1000000;
	if (ts.tv_nsec >= 1000000000) { ts.tv_nsec -= 1000000000; ts.tv_sec++; }
	SceUInt64 t0 = sceKernelGetProcessTimeWide ();
	int r = sem_timedwait (&s, &ts), e = errno;
	unsigned ms = (unsigned) ((sceKernelGetProcessTimeWide () - t0) / 1000);
	int v = 0;
	sem_getvalue (&s, &v);
	snprintf (buf, n, "%s (sem_timedwait -> %d%s after %u ms, value %d)", r == 0 ? "BROKEN: returned without a post" : "ok: timed out",
	          r, r ? (e == ETIMEDOUT ? " ETIMEDOUT" : " other error") : "", ms, v);
	sem_destroy (&s);
	return buf;
}

static void diag_sem_selftest (void)
{
	char a [160], b [160];
	sem_selftest (shepherd_stock_sem_post, a, sizeof (a));
	sem_selftest (sem_post, b, sizeof (b));
	LOG ("H0 sem_post self-test: vitasdk stock sem_post %s | this app's corrected sem_post %s", a, b);
}

