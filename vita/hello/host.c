extern SceUID __real_sceKernelCreateThread (const char *name, SceKernelThreadEntry entry, int prio, SceSize stack, SceUInt attr, int cpu, const SceKernelThreadOptParam *opt);
SceUID __wrap_sceKernelCreateThread (const char *name, SceKernelThreadEntry entry, int prio, SceSize stack, SceUInt attr, int cpu, const SceKernelThreadOptParam *opt);
