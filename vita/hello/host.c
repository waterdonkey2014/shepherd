/* build.sh links with -Wl,--wrap=sceKernelCreateThread (diag only): every thread the app creates (pthreads, Mono's) is recorded */
#define DIAG_MAX_THREADS 48
static volatile SceUID g_diag_threads [DIAG_MAX_THREADS];
