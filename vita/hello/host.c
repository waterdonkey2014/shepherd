/* before the log exists (the mode picks the log file): SHEPHERD_DIAG_MODE in hello-diag-env.txt, else a 4 s window on the screen */
static void choose_diag_mode_early (void)
{
	void *data;
	unsigned size;
	if (read_file (ENV_PATH, &data, &size) == 0) {
		char *m = strstr ((char *) data, "SHEPHERD_DIAG_MODE=");
		if (m) {
			m += 19;
			g_diag_mode = !strncmp (m, "repro", 5) ? 1 : !strncmp (m, "gcfirst", 7) ? 2 : 0;
			g_diag_mode_how = " (SHEPHERD_DIAG_MODE in hello-diag-env.txt)";
		}
		free (data);
	}
	if (!*g_diag_mode_how) {
		if (g_screen)
			psvDebugScreenPuts ("Shepherd Hello Diag: press L now = REPRO (the 2026-10-07 crash, with details), R = GC-FIRST, nothing = NORMAL (4 s)\n");
		SceCtrlData pad;
		for (int i = 0; i < 80 && !g_diag_mode; ++i) {
			memset (&pad, 0, sizeof (pad));
			sceCtrlPeekBufferPositive (0, &pad, 1);
			if (pad.buttons & (SCE_CTRL_LTRIGGER | SCE_CTRL_L1))
				g_diag_mode = 1;
			else if (pad.buttons & (SCE_CTRL_RTRIGGER | SCE_CTRL_R1))
				g_diag_mode = 2;
			else
				sceKernelDelayThread (50 * 1000);
		}
		g_diag_mode_how = g_diag_mode ? " (button held)" : " (no button)";
	}
	if (g_diag_mode)
		snprintf (g_log_path, sizeof (g_log_path), LOG_DIR "/hello-diag-%s.txt", g_diag_mode_name [g_diag_mode]);
}
